SELECT
    HASO_PER_FACT AS "NumPeriodo",
    ASO_IDENTIFICACION AS "CEDULA_ASOCIADO",
    CAST(
    ASO_PRIMER_NOMBRE || ' ' || ASO_SEGUNDO_NOMBRE || ' ' || 
    ASO_PRIMER_APELLIDO || ' ' || ASO_SEGUNDO_APELLIDO 
    AS VARCHAR(200)
    ) AS "NOMBRE_ASOCIADO",
    TIPO_CLIENTE AS "TIPO_CLIENTE",
    COALESCE(HASO_EDAD_CARTERA_INI,0) AS "EDAD_CARTERA_INICIAL",
    COALESCE(HASO_EDAD_CARTERA_HOY,0) AS "EDAD_CARTERA_HOY",
    ESTM_NOMBRE AS "ESTADO_COOMEVA_HOY",
    ANTIGUEDAD AS "ANTIGUEDAD_DEL_ASOCIADO_EN_COOMEVA",
    ASO_CUOTAS_CANCELADAS_APORTES AS "NO_CUOTAS_CANCELADAS",
    ASO_SUBCAMPANNA_ASIGNADA AS "SUBCAMPANA"
FROM GCC_REPORTE10;