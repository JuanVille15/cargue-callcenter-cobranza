SELECT
    GCC_TIPO_ALFABETICO,
    ASO_IDENTIFICACION,
    CON_CODIGO,
    FACT_INTERES_MORA_DIA,
    FACT_VALOR_CUOTA_MES,
    FACT_VALOR_VENCIDO,
    FACT_VALOR_CUOTA_MES + FACT_VALOR_VENCIDO AS TOTAL,
    FACT_NUMERO_CUOTAS_ATRASADAS,
    FACT_NUMERO_PAGARE,
    COR_NUMERO_CORTE
FROM GRC.STG_GCC_FACTURACION
WHERE 
    CON_CODIGO in ('AUX.FUN.','SOLIDAR.','SOLIDARE','APORTES','CALAMID','RECREA');