SELECT
    INF.PERIODO,
    INF.ASO_IDENTIFICACION,
    SASO.ASO_NOMBRE_COMPLETO,
    INF.PAGARE,
    INF.LINEA_CREDITO,
    INF.PRODUCTO,
    INF.SALDO_TOTAL AS SALDO_SIN_FACTURAR,
    INF.CAPITAL_VENCIDO AS VALOR_VENCIDO,
    FAC.FACT_VALOR_CUENTA_COBRAR AS CXC,
    INF.CAPITAL_X_VENCER AS CUOTA_MES,
    FAC.FACT_INTERES_MORA_DIA,
    FAC.FACT_INTERES_MORA_CORTE,
    INF.VALOR_CUOTAS_MORA AS VALOR_TOTAL_A_PAGAR,
    INF.SALDO_CAPITAL,
    (INF.SALDO_TOTAL + INF.CAPITAL_VENCIDO + FAC.FACT_VALOR_CUENTA_COBRAR + INF.CAPITAL_X_VENCER + FAC.FACT_INTERES_MORA_DIA)
        - INF.SALDO_CAPITAL AS INTERESES_TOTALES,
    INF.SALDO_TOTAL + INF.CAPITAL_VENCIDO + FAC.FACT_VALOR_CUENTA_COBRAR + INF.CAPITAL_X_VENCER + FAC.FACT_INTERES_MORA_DIA AS SALDO_TOTAL,
    INF.CAPITAL_VENCIDO + FAC.FACT_INTERES_MORA_DIA AS VENCIDO_TOTAL,
    FAC.FACT_DIAS_DE_MORA,
    FAC.FACT_NUMERO_CUOTAS_ATRASADAS AS CUOTAS_ATRASADAS,
    FAC.FACT_CUOTA_PAGADA AS CUOTAS_PAGADAS,
    FAC.FACT_CUOTAS_PACTADAS - FAC.FACT_CUOTA_PAGADA AS CUOTAS_PENDIENTES,
    FAC.FACT_CUOTAS_PACTADAS AS CUOTAS_PACTADAS,
    INF.ESTADO_CREDITO,
    STM.ESTM_NOMBRE,
    SASO.ASO_FECHA_CAMBIO_ESTADO_MULT,
    FAC.FACT_FECHA_CREA,
    INF.FEC_ACTUALIZACION,
    INF.FEC_APERTURA AS FECHA_DESEMBOLSO,
    INF.FEC_VENCIMIENTO AS FECHA_CIERRE,
    INF.TASA_INICIAL AS TASA_NOMINAL_ANUAL
FROM GRC.STG_GCC_SAC_INFOOBL INF
LEFT OUTER JOIN GRC.STG_GCC_FACTURACION FAC
    ON INF.PAGARE = FAC.FACT_NUMERO_PAGARE
LEFT OUTER JOIN GRC.STG_GCC_ASOCIADO SASO
    ON INF.ASO_IDENTIFICACION = SASO.ASO_IDENTIFICACION
LEFT OUTER JOIN GRC.GCC_ESTADOS_MULTIACTIVA STM
    ON SASO.ESTM_CODIGO = STM.ESTM_CODIGO
WHERE INF.PRODUCTO IN (
    'CRESOLID',
    'CREDIASO',
    'CRPATRIM',
    'CRCUOINI',
    'CR.LI.M',
    'CR.LIBRM',
    'REESTCRS',
    'CR.EMP.M',
    'REEST CO',
    'CR.EDUCM'
);